export const allPlaces = collections.flatMap(collection => collection.places);
export const places = Object.fromEntries(allPlaces.map(place => [place.id, place]));

export function dailyPlace(date = new Date()) {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return allPlaces[day % allPlaces.length];
}

export function randomPlace(previousKey, random = Math.random) {
  const candidates = allPlaces.filter(place => place.id !== previousKey);
  return candidates[Math.floor(random() * candidates.length)];
}
